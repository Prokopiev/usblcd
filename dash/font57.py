def glyph(ch):
    """The 5x7 bitmap for *ch* as 7 strings of 5 chars ('#' = lit)."""
    c = ch.upper()
    g = FONT.get(c)
    if g is None:
        g = FONT.get('?')
    return g.split('\n')
